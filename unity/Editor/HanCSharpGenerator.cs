using System;
using System.IO;
using System.Text;
using UnityEngine;

/// <summary>한씨가 소유하는 C# 파일만 갱신한다. 사용자 작성 C#과 .meta는 덮어쓰지 않는다.</summary>
public static class HanCSharpGenerator
{
    private const string Header = "// <auto-generated by HanCSharp> source=";

    public static bool Owns(string csPath, string sourcePath)
    {
        if (!File.Exists(csPath)) return false;
        using (var reader = new StreamReader(csPath))
        {
            return reader.ReadLine() == Header + sourcePath;
        }
    }

    public static bool Generate(string sourcePath, HanCSharpSettings settings)
    {
        string target = Path.ChangeExtension(sourcePath, ".cs");
        if (File.Exists(target) && !Owns(target, sourcePath))
        {
            Debug.LogError("한씨: 사용자 작성 파일과 경로가 겹칩니다. 덮어쓰지 않습니다: " + target);
            return false;
        }
        if (!File.Exists(settings.CompilerPath))
        {
            Debug.LogError("한씨: 변환기 경로를 설정하세요: " + settings.CompilerPath);
            return false;
        }
        string temporary = Path.GetFullPath("Library/HanCSharp/" + Guid.NewGuid().ToString("N") + ".cs");
        Directory.CreateDirectory(Path.GetDirectoryName(temporary));
        try
        {
            bool success = HanCSharpProcess.Convert(settings.DotNetPath, settings.CompilerPath,
                Path.GetFullPath(sourcePath), temporary, out string message, settings.EmitSourceMap);
            string content = Header + sourcePath + "\n";
            if (success) content += File.ReadAllText(temporary);
            else
            {
                // 실패한 소스 대신 이전 코드를 실행하는 일을 막는다. 소스를 고치면 다시 생성된다.
                content += "#error HanCSharp 변환 실패. 원본 .han 및 Console 오류를 확인하세요.\n";
                Debug.LogError(message);
            }
            if (!File.Exists(target) || File.ReadAllText(target) != content)
            {
                File.WriteAllText(target, content, new UTF8Encoding(false));
                return true;
            }
            return false;
        }
        catch (Exception exception)
        {
            Debug.LogError("한씨: " + exception.Message);
            File.WriteAllText(target, Header + sourcePath + "\n#error HanCSharp 변환기 실행 실패. Console을 확인하세요.\n", new UTF8Encoding(false));
            return true;
        }
        finally
        {
            if (File.Exists(temporary)) File.Delete(temporary);
        }
    }

    public static void UpdateOwnership(string csPath, string oldSource, string newSource)
    {
        if (!Owns(csPath, oldSource)) return;
        string content = File.ReadAllText(csPath);
        int end = content.IndexOf('\n');
        File.WriteAllText(csPath, Header + newSource + (end >= 0 ? content.Substring(end) : "\n"), new UTF8Encoding(false));
    }
}
